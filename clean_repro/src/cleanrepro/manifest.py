"""Builds benchmark/manifest.csv by scanning the original benchmark folders (no hand-typed rows).

One row per program under test:
  small (0_100 LOC)   : cat1_scripts / cat2_functions / cat3_classes, module = example.py
  p1 (100_300 LOC p1) : cat1 / cat2 / cat3, module = example.py (inputs of the iterative RQ2 runs)
  p2 (100_300 LOC p2) : sampleN, module = the non-test .py file in "pynguin coverage/sampleN"

Categories: small and p1 take the category of their folder. p2 has no category in the repository;
it is derived by a documented rule (module defines a top-level class -> 3, else 2) and marked as
derived (`category_source`).  Of the rules tried, this one reproduces the paper's Table 2 Cat 2 row
from the saved reports (77.44 / 88.78, t-test p = 0.169); see README.

Run with the `exec` environment (needs mccabe):  python -m cleanrepro.manifest
"""
from __future__ import annotations

import ast
import csv
import io
import re
import tokenize
from pathlib import Path

import mccabe

from .integrity import sha256_file
from .paths import BENCH, P1_DIRS, P2_GPT, P2_PYN, SMALL_DIRS, rel

PYNGUIN_HEADER = "Test cases automatically generated by Pynguin"
FIELDS = [
    "sample_id", "group", "category", "category_source", "name", "module_file", "module_path",
    "module_sha256", "loc", "sloc", "n_functions", "n_classes", "n_top_level_classes", "max_mccabe",
    "parses_py310",
    "reads_stdin", "source_url",
    "pynguin_suite", "pynguin_suite_is_pynguin", "pynguin_stmt_report", "pynguin_branch_report",
    "chatgpt_suite", "chatgpt_stmt_report", "chatgpt_branch_report", "chatgpt_compilation_report",
    "developer_suite", "developer_module_name", "notes",
]


def code_metrics(path: Path) -> dict:
    src = path.read_text(encoding="utf-8", errors="replace")
    loc = len(src.splitlines())
    sloc = 0
    try:
        toks = tokenize.generate_tokens(io.StringIO(src).readline)
        code_lines = set()
        for t in toks:
            if t.type not in (tokenize.COMMENT, tokenize.NL, tokenize.NEWLINE, tokenize.INDENT,
                              tokenize.DEDENT, tokenize.ENDMARKER, tokenize.STRING):
                code_lines.update(range(t.start[0], t.end[0] + 1))
        sloc = len(code_lines)
    except (tokenize.TokenError, IndentationError, SyntaxError):
        sloc = -1
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return dict(loc=loc, sloc=sloc, n_functions="", n_classes="", max_mccabe="",
                    parses_py310=False, reads_stdin="input(" in src)
    funcs = [n for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
    classes = [n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]
    visitor = mccabe.PathGraphingAstVisitor()
    visitor.preorder(tree, visitor)
    comps = [g.complexity() for g in visitor.graphs.values()]
    reads_stdin = any(isinstance(n, ast.Call) and getattr(n.func, "id", "") == "input"
                      for n in ast.walk(tree)) or "sys.stdin" in src
    top_classes = [n for n in tree.body if isinstance(n, ast.ClassDef)]
    return dict(loc=loc, sloc=sloc, n_functions=len(funcs), n_classes=len(classes),
                n_top_level_classes=len(top_classes),
                max_mccabe=max(comps) if comps else 0, parses_py310=True, reads_stdin=reads_stdin)


def is_pynguin(path: Path | None) -> bool | str:
    if path is None or not path.exists():
        return ""
    return PYNGUIN_HEADER in path.read_text(errors="replace")[:300]


def opt(p: Path) -> str:
    return rel(p) if p.exists() else ""


def small_rows() -> list[dict]:
    rows = []
    for cat, d in SMALL_DIRS.items():
        for prog in sorted(p for p in d.iterdir() if p.is_dir() and not p.name.startswith("__")):
            mod = prog / "example.py"
            if not mod.exists():
                continue
            dev = sorted(prog.glob("*_test.py"))
            pyn = prog / "test_example.py"
            row = dict(sample_id=f"small_cat{cat}/{prog.name}", group="small", category=cat,
                       category_source="folder", name=prog.name, module_file="example.py",
                       module_path=rel(mod), module_sha256=sha256_file(mod),
                       pynguin_suite=opt(pyn), pynguin_suite_is_pynguin=is_pynguin(pyn),
                       pynguin_stmt_report=opt(prog / "line_coverage.txt"),
                       pynguin_branch_report=opt(prog / "branch_coverage.txt"),
                       developer_suite=rel(dev[0]) if dev else "",
                       developer_module_name=dev[0].name[:-len("_test.py")] if dev else "")
            row.update(code_metrics(mod))
            rows.append(row)
    return rows


def p1_rows() -> list[dict]:
    rows = []
    for cat, d in P1_DIRS.items():
        urls = {}
        a = d / "a.txt"
        if a.exists():
            for line in a.read_text(errors="replace").splitlines():
                m = re.match(r"\s*(\d+)\s*-\s*(\S+)(.*)", line)
                if m:
                    urls[f"s{m[1]}"] = (m[2], m[3].strip(" -"))
        for s in sorted((p for p in d.iterdir() if p.is_dir()), key=lambda p: int(p.name[1:])):
            mod = s / "example.py"
            url, note = urls.get(s.name, ("", ""))
            row = dict(sample_id=f"p1_cat{cat}/{s.name}", group="p1", category=cat,
                       category_source="folder", name=s.name, module_file="example.py",
                       module_path=rel(mod), module_sha256=sha256_file(mod), source_url=url,
                       notes=f"a.txt: {note}" if note else "")
            row.update(code_metrics(mod))
            rows.append(row)
    return rows


def p2_rows() -> list[dict]:
    rows = []
    for s in sorted((p for p in P2_PYN.iterdir() if p.is_dir() and p.name.startswith("sample")),
                    key=lambda p: int(p.name[6:])):
        mods = [p for p in s.glob("*.py") if not p.name.startswith("test_")]
        if len(mods) != 1:
            raise SystemExit(f"{s}: expected one module under test, found {mods}")
        mod = mods[0]
        stem = mod.stem
        tests = [p for p in s.glob("test_*.py") if not p.stem.endswith("_old")]
        pyn = tests[0] if len(tests) == 1 else None
        stmt = [p for p in s.glob("statement_coverage*.txt") if not p.stem.endswith("_old")]
        br = list(s.glob("branch_coverage*.txt"))
        g = P2_GPT / s.name
        m = code_metrics(mod)
        notes = []
        if len(tests) > 1 or (s / f"test_{stem}_old.py").exists():
            notes.append("pynguin folder also holds an *_old suite/report (ignored)")
        row = dict(sample_id=f"p2/{s.name}", group="p2", category="", name=s.name,
                   module_file=mod.name, module_path=rel(mod), module_sha256=sha256_file(mod),
                   pynguin_suite=rel(pyn) if pyn else "", pynguin_suite_is_pynguin=is_pynguin(pyn),
                   pynguin_stmt_report=rel(stmt[0]) if len(stmt) == 1 else "",
                   pynguin_branch_report=rel(br[0]) if len(br) == 1 else "",
                   chatgpt_suite=opt(g / "test_example.py"),
                   chatgpt_stmt_report=opt(g / "statement_coverage.txt"),
                   chatgpt_branch_report=opt(g / "branch_coverage.txt"),
                   chatgpt_compilation_report=opt(g / "compilation_report.txt"),
                   category_source="derived: top-level class defined -> 3 else 2 (not in repository; "
                                   "this rule reproduces the paper's Table 2 Cat 2 row, see README)",
                   notes="; ".join(notes))
        row["category"] = 3 if m.get("n_top_level_classes") else 2
        row.update(m)
        rows.append(row)
    return rows


def build() -> list[dict]:
    rows = small_rows() + p1_rows() + p2_rows()
    BENCH.mkdir(parents=True, exist_ok=True)
    with open(BENCH / "manifest.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in FIELDS})
    return rows


if __name__ == "__main__":
    rows = build()
    from collections import Counter
    print(Counter((r["group"], r["category"]) for r in rows))
