import csv
import tempfile
import unittest
from collections import Counter
from pathlib import Path

from cleanroom import integrity, manifest, paths


def _write(root, rel, text):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


class TestSyntheticLayout(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        r = self.root = Path(self.tmp.name)
        s = "0_100 LOC"
        _write(r, f"{s}/a1_script.py", "# helper, not a program\n")
        _write(r, f"{s}/cat1_scripts/stdin/example.py", "n = int(input())\nprint(n)\n")
        _write(r, f"{s}/cat1_scripts/nounit/example.py", "print(sum([1, 2]))\n")
        _write(r, f"{s}/cat2_functions/ok/example.py", "def f(x):\n    return x\n")
        _write(r, f"{s}/cat2_functions/ok/ok.py", "def f(x):\n    pass\n")
        _write(r, f"{s}/cat2_functions/ok/ok_test.py", "import unittest\nfrom ok import f\n")
        _write(r, f"{s}/cat2_functions/ok/test_example.py",
               "# Test cases automatically generated by Pynguin (https://www.pynguin.eu).\n")
        _write(r, f"{s}/cat2_functions/py2/example.py", 'print "x"\n')
        _write(r, f"{s}/cat3_classes/missing/notes.txt", "no target\n")
        _write(r, f"{s}/cat3_classes/dup/example.py", "def f(x):\n    return x\n")
        p2 = "100_300 LOC p2/pynguin coverage"
        _write(r, f"{p2}/sample1/mod.py", "import os\nclass A:\n    pass\n")
        _write(r, f"{p2}/sample1/test_mod.py", "")
        _write(r, "100_300 LOC p2/ChatGPT coverage/sample1/test_example.py", "")
        _write(r, f"{p2}/sample2/mod.py", "from .x import y\nimport requests\ndef g(): pass\n")
        _write(r, f"{p2}/sample10/a.py", "def g(): pass\n")
        _write(r, f"{p2}/sample10/b.py", "def h(): pass\n")
        for cat in ("cat1", "cat2", "cat3"):
            _write(r, f"100_300 LOC p1/{cat}/s1/example.py", "import pymongo\n")
        self.programs = {p.program_id: p for p in manifest.build_manifest(r)}

    def tearDown(self):
        self.tmp.cleanup()

    def status(self, pid):
        return self.programs[pid].status

    def test_discovery(self):
        self.assertEqual(sorted(self.programs), sorted([
            "small/cat1_scripts/nounit", "small/cat1_scripts/stdin",
            "small/cat2_functions/ok", "small/cat2_functions/py2",
            "small/cat3_classes/dup", "small/cat3_classes/missing",
            "p2/sample1", "p2/sample2", "p2/sample10",
            "p1/cat1/s1", "p1/cat2/s1", "p1/cat3/s1"]))
        self.assertEqual([p for p in self.programs if p.startswith("p2/")],
                         ["p2/sample1", "p2/sample2", "p2/sample10"])  # numeric order

    def test_statuses(self):
        self.assertEqual(self.status("small/cat1_scripts/stdin"), manifest.NEEDS_DECISION_STDIN)
        self.assertEqual(self.status("small/cat1_scripts/nounit"), manifest.NEEDS_DECISION_NO_UNIT)
        self.assertEqual(self.status("small/cat2_functions/ok"), manifest.CANDIDATE)
        self.assertEqual(self.status("small/cat2_functions/py2"), manifest.INELIGIBLE_PARSE)
        self.assertEqual(self.status("small/cat3_classes/missing"), manifest.INELIGIBLE_TARGET)
        self.assertEqual(self.status("p2/sample1"), manifest.CANDIDATE)
        self.assertEqual(self.status("p2/sample2"), manifest.PENDING_CONTEXT)
        self.assertEqual(self.status("p2/sample10"), manifest.INELIGIBLE_TARGET)
        for cat in ("cat1", "cat2", "cat3"):
            self.assertEqual(self.status(f"p1/{cat}/s1"), manifest.OUT_OF_SCOPE)

    def test_reasons(self):
        r = self.programs["p2/sample2"].reasons
        self.assertIn("unresolved imports: requests", r)
        self.assertIn("relative imports: .x", r)
        self.assertIn("2 candidate modules: a.py, b.py", self.programs["p2/sample10"].reasons)

    def test_target_excludes_itself_from_local_modules(self):
        ok = self.programs["small/cat2_functions/ok"]
        self.assertEqual(ok.facts.imports_local, [])

    def test_dev_tests_and_stub(self):
        ok = self.programs["small/cat2_functions/ok"]
        self.assertEqual(ok.dev_test_files, ["0_100 LOC/cat2_functions/ok/ok_test.py"])
        self.assertEqual(ok.dev_test_imports, ["ok"])
        self.assertTrue(ok.dev_test_module_is_stub)
        self.assertFalse(ok.dev_test_module_matches_target)
        self.assertEqual(ok.saved_suites, ["pynguin:0_100 LOC/cat2_functions/ok/test_example.py"])

    def test_saved_suites_p2(self):
        self.assertEqual(self.programs["p2/sample1"].saved_suites, [
            "unlabelled:100_300 LOC p2/pynguin coverage/sample1/test_mod.py",
            "chatgpt(per README):100_300 LOC p2/ChatGPT coverage/sample1/test_example.py"])

    def test_duplicates(self):
        self.assertEqual(self.programs["small/cat3_classes/dup"].duplicate_of,
                         ["small/cat2_functions/ok"])
        self.assertIn("identical target bytes to: small/cat2_functions/ok",
                      self.programs["small/cat3_classes/dup"].reasons)

    def test_csv_round_trip(self):
        out = self.root / "m.csv"
        manifest.write_manifest(list(self.programs.values()), out)
        rows = manifest.read_manifest(out)
        self.assertEqual(len(rows), len(self.programs))
        self.assertTrue(all(r["execution_verified"] == "False" for r in rows))


@unittest.skipUnless(paths.INVENTORY_TSV.exists(), "inventory not built yet")
class TestRealSnapshot(unittest.TestCase):
    def test_counts_and_originals_untouched(self):
        integrity.assert_originals_intact()
        programs = manifest.build_manifest(paths.REPO_ROOT)
        integrity.assert_originals_intact()
        groups = Counter(f"{p.set}/{p.category}" for p in programs)
        self.assertEqual(groups, Counter({
            "small/cat1_scripts": 21, "small/cat2_functions": 19, "small/cat3_classes": 20,
            "p2/unlabelled": 43, "p1/cat1": 1, "p1/cat2": 20, "p1/cat3": 20}))
        self.assertTrue(all(p.target for p in programs))

    @unittest.skipUnless(paths.MANIFEST_CSV.exists(), "manifest not built yet")
    def test_committed_manifest_is_reproducible(self):
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "m.csv"
            manifest.write_manifest(manifest.build_manifest(paths.REPO_ROOT), out)
            self.assertEqual(out.read_bytes(), paths.MANIFEST_CSV.read_bytes())


if __name__ == "__main__":
    unittest.main()
