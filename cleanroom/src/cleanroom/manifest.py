"""Benchmark manifest: one row per program with static eligibility facts.

Statuses are *pre-execution*. No program is declared eligible here: a program
becomes eligible only after it has been imported and run in the pinned
Python 3.10 environment (a later, separately approved step).

    python3 -m cleanroom.manifest
"""
from __future__ import annotations

import csv
import hashlib
import json
import sys
from collections import defaultdict
from dataclasses import asdict, dataclass, field
from pathlib import Path

from . import integrity, paths
from .static_analysis import SourceFacts, analyse

SMALL_ROOT = "0_100 LOC"
SMALL_CATEGORIES = ("cat1_scripts", "cat2_functions", "cat3_classes")
P1_ROOT = "100_300 LOC p1"
P1_CATEGORIES = ("cat1", "cat2", "cat3")
P2_ROOT = "100_300 LOC p2"
P2_MODULE_DIR = "pynguin coverage"
P2_CHATGPT_DIR = "ChatGPT coverage"
IN_SCOPE_SETS = ("small", "p2")  # decision 2: p1 deferred

# Pre-execution statuses, in order of precedence.
OUT_OF_SCOPE = "OUT_OF_SCOPE"
INELIGIBLE_TARGET = "INELIGIBLE_TARGET"
INELIGIBLE_PARSE = "INELIGIBLE_PARSE"
NEEDS_DECISION_STDIN = "NEEDS_DECISION_STDIN"
NEEDS_DECISION_NO_UNIT = "NEEDS_DECISION_NO_UNIT"
PENDING_CONTEXT = "PENDING_CONTEXT"
CANDIDATE = "CANDIDATE"
STATUSES = (CANDIDATE, PENDING_CONTEXT, NEEDS_DECISION_STDIN, NEEDS_DECISION_NO_UNIT,
            INELIGIBLE_PARSE, INELIGIBLE_TARGET, OUT_OF_SCOPE)

STATUS_MEANING = {
    CANDIDATE: "target parses as Python 3.10 and imports only the standard library or files "
               "present next to it; eligibility still requires an execution check",
    PENDING_CONTEXT: "imports modules that are neither standard library nor present in the "
                     "repository (third-party packages or missing sibling modules); needs "
                     "dependency/context reconstruction, then an execution check",
    NEEDS_DECISION_STDIN: "reads standard input when imported, so it cannot be imported by a "
                          "unit test as-is; handling requires an explicit decision",
    NEEDS_DECISION_NO_UNIT: "defines no top-level function or class: all work happens at import "
                            "time, so there is no unit to call; handling requires an explicit decision",
    INELIGIBLE_PARSE: "target does not parse as Python 3.10",
    INELIGIBLE_TARGET: "no unique target file",
    OUT_OF_SCOPE: "set excluded from the initial scope (p1, decision 2)",
}

LIST_FIELDS = ("imports_stdlib", "imports_relative", "imports_local", "imports_unresolved",
               "imports_optional_unresolved", "imports_type_checking", "dev_test_files",
               "dev_test_imports", "saved_suites", "duplicate_of", "reasons")


@dataclass
class Program:
    program_id: str
    set: str
    category: str
    name: str
    directory: str
    target: str = ""
    target_sha256: str = ""
    in_scope: bool = True
    dev_test_files: list[str] = field(default_factory=list)
    dev_test_imports: list[str] = field(default_factory=list)
    dev_test_module_is_stub: bool = False
    dev_test_module_matches_target: bool = False
    saved_suites: list[str] = field(default_factory=list)
    duplicate_of: list[str] = field(default_factory=list)
    status: str = ""
    reasons: list[str] = field(default_factory=list)
    facts: SourceFacts = field(default_factory=SourceFacts)

    def row(self) -> dict:
        d = asdict(self)
        d.update(d.pop("facts"))
        for k, v in d.items():
            if isinstance(v, list):
                d[k] = ";".join(v)
        d["execution_verified"] = False
        return d


def _rel(repo: Path, p: Path) -> str:
    return p.relative_to(repo).as_posix()


def _local_module_names(directory: Path) -> set[str]:
    names = {p.stem for p in directory.glob("*.py")}
    names |= {p.name for p in directory.iterdir() if p.is_dir() and (p / "__init__.py").exists()}
    return names


def _suite_generator(path: Path) -> str:
    head = path.read_text(encoding="utf-8", errors="replace")[:300].lower()
    return "pynguin" if "generated by pynguin" in head else "unlabelled"


def _discover_small(repo: Path) -> list[Program]:
    programs = []
    for cat in SMALL_CATEGORIES:
        for d in sorted(p for p in (repo / SMALL_ROOT / cat).iterdir() if p.is_dir()):
            prog = Program(f"small/{cat}/{d.name}", "small", cat, d.name, _rel(repo, d))
            if (d / "example.py").is_file():
                prog.target = _rel(repo, d / "example.py")
            prog.dev_test_files = sorted(_rel(repo, p) for p in d.glob("*_test.py"))
            if (d / "test_example.py").is_file():
                t = d / "test_example.py"
                prog.saved_suites = [f"{_suite_generator(t)}:{_rel(repo, t)}"]
            programs.append(prog)
    return programs


def _discover_p1(repo: Path) -> list[Program]:
    programs = []
    for cat in P1_CATEGORIES:
        for d in sorted(p for p in (repo / P1_ROOT / cat).iterdir() if p.is_dir()):
            prog = Program(f"p1/{cat}/{d.name}", "p1", cat, d.name, _rel(repo, d), in_scope=False)
            if (d / "example.py").is_file():
                prog.target = _rel(repo, d / "example.py")
            programs.append(prog)
    return programs


def _sample_key(p: Path) -> tuple[int, str]:
    digits = "".join(c for c in p.name if c.isdigit())
    return (int(digits) if digits else -1, p.name)


def _discover_p2(repo: Path) -> list[Program]:
    programs = []
    base = repo / P2_ROOT / P2_MODULE_DIR
    for d in sorted((p for p in base.iterdir() if p.is_dir()), key=_sample_key):
        # p2 category labels are not recorded in the repository.
        prog = Program(f"p2/{d.name}", "p2", "unlabelled", d.name, _rel(repo, d))
        modules = sorted(p for p in d.glob("*.py") if not p.name.startswith("test_"))
        if len(modules) == 1:
            prog.target = _rel(repo, modules[0])
        else:
            prog.reasons.append(f"{len(modules)} candidate modules: "
                                + ", ".join(m.name for m in modules))
        suites = [f"{_suite_generator(t)}:{_rel(repo, t)}" for t in sorted(d.glob("test_*.py"))]
        chatgpt = repo / P2_ROOT / P2_CHATGPT_DIR / d.name / "test_example.py"
        if chatgpt.is_file():
            suites.append(f"chatgpt(per README):{_rel(repo, chatgpt)}")
        prog.saved_suites = suites
        programs.append(prog)
    return programs


def _analyse_dev_tests(repo: Path, prog: Program) -> None:
    """Which local modules the developer tests import, and whether those are stubs."""
    imported: set[str] = set()
    for rel in prog.dev_test_files:
        test = repo / rel
        facts = analyse(test, _local_module_names(test.parent))
        imported |= set(facts.imports_local)
    prog.dev_test_imports = sorted(imported)
    d = repo / prog.directory
    modules = [d / f"{m}.py" for m in imported if (d / f"{m}.py").is_file()]
    prog.dev_test_module_is_stub = any(analyse(m).is_stub for m in modules)
    target = (repo / prog.target).read_bytes() if prog.target else None
    prog.dev_test_module_matches_target = any(m.read_bytes() == target for m in modules)


def _assign_status(prog: Program) -> None:
    f = prog.facts
    reasons = prog.reasons
    if not prog.in_scope:
        prog.status = OUT_OF_SCOPE
        return
    if not prog.target:
        prog.status = INELIGIBLE_TARGET
        if not reasons:
            reasons.append("no target file found")
        return
    if not f.parses:
        prog.status = INELIGIBLE_PARSE
        reasons.append(f.parse_error)
        return
    no_unit = f.n_functions + f.n_classes == 0
    unresolved = f.imports_unresolved + f.imports_relative + f.imports_optional_unresolved
    if f.stdin_at_import:
        reasons.append("reads stdin at import time")
    if no_unit:
        reasons.append("no top-level function or class (no callable unit)")
    if f.imports_unresolved:
        reasons.append("unresolved imports: " + ", ".join(f.imports_unresolved))
    if f.imports_relative:
        reasons.append("relative imports: " + ", ".join(f.imports_relative))
    if f.imports_optional_unresolved:
        reasons.append("optional (try/except) unresolved imports: "
                       + ", ".join(f.imports_optional_unresolved))
    if f.stdin_at_import:
        prog.status = NEEDS_DECISION_STDIN
    elif no_unit:
        prog.status = NEEDS_DECISION_NO_UNIT
    elif unresolved:
        prog.status = PENDING_CONTEXT
    else:
        prog.status = CANDIDATE
    if prog.duplicate_of:
        reasons.append("identical target bytes to: " + ", ".join(prog.duplicate_of))


def build_manifest(repo: Path) -> list[Program]:
    programs = _discover_small(repo) + _discover_p2(repo) + _discover_p1(repo)
    for prog in programs:
        if prog.target:
            target = repo / prog.target
            prog.target_sha256 = hashlib.sha256(target.read_bytes()).hexdigest()
            prog.facts = analyse(target, _local_module_names(target.parent) - {target.stem})
        if prog.dev_test_files:
            _analyse_dev_tests(repo, prog)
    by_hash: dict[str, list[str]] = defaultdict(list)
    for prog in programs:
        if prog.target_sha256:
            by_hash[prog.target_sha256].append(prog.program_id)
    for prog in programs:
        if prog.target_sha256:
            prog.duplicate_of = [p for p in by_hash[prog.target_sha256] if p != prog.program_id]
    for prog in programs:
        _assign_status(prog)
    return programs


def write_manifest(programs: list[Program], path: Path) -> None:
    rows = [p.row() for p in programs]
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def read_manifest(path: Path) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def main() -> int:
    repo = paths.REPO_ROOT
    before = integrity.assert_originals_intact(repo, paths.INVENTORY_TSV)
    programs = build_manifest(repo)
    write_manifest(programs, paths.MANIFEST_CSV)
    after = integrity.assert_originals_intact(repo, paths.INVENTORY_TSV)
    counts: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for p in programs:
        counts[f"{p.set}/{p.category}"][p.status] += 1
    summary = {
        "manifest": paths.MANIFEST_CSV.relative_to(paths.CLEANROOM).as_posix(),
        "manifest_sha256": hashlib.sha256(paths.MANIFEST_CSV.read_bytes()).hexdigest(),
        "programs": len(programs),
        "by_group_and_status": {k: dict(v) for k, v in sorted(counts.items())},
        "integrity_before": before.to_dict()["passed"],
        "integrity_after": after.to_dict()["passed"],
    }
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
