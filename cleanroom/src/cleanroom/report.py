"""Generate the eligibility report from manifest.csv (no hand-typed numbers).

    python3 -m cleanroom.report
"""
from __future__ import annotations

import hashlib
import json
import sys
from collections import Counter, defaultdict

from . import integrity, manifest, paths

GROUP_ORDER = ["small/cat1_scripts", "small/cat2_functions", "small/cat3_classes",
               "p2/unlabelled", "p1/cat1", "p1/cat2", "p1/cat3"]
NOMINAL_LOC = {"small": (0, 100), "p2": (100, 300), "p1": (100, 300)}


def _split(v: str) -> list[str]:
    return [x for x in v.split(";") if x]


def _ignored_files() -> list[str]:
    """.py files in the benchmark tree that are not program targets (helpers)."""
    out = []
    for root in (manifest.SMALL_ROOT, manifest.P1_ROOT, manifest.P2_ROOT):
        base = paths.REPO_ROOT / root
        out += [p for p in base.glob("*.py")]
        out += [p for p in base.glob("*/*.py")]
    return sorted(p.relative_to(paths.REPO_ROOT).as_posix() for p in out)


def render(rows: list[dict]) -> str:
    manifest_sha = hashlib.sha256(paths.MANIFEST_CSV.read_bytes()).hexdigest()
    inv_sha = hashlib.sha256(paths.INVENTORY_TSV.read_bytes()).hexdigest()
    L = []
    w = L.append
    w("# A3 — Benchmark eligibility report (pre-execution)\n")
    w("Generated by `python3 -m cleanroom.report` from `benchmark/manifest.csv`. "
      "Every number below is computed from that file.\n")
    w(f"- Snapshot commit: `{paths.SNAPSHOT_COMMIT}` (upstream equivalence **not verified**)")
    w(f"- `benchmark/originals_sha256.tsv` SHA-256: `{inv_sha}`")
    w(f"- `benchmark/manifest.csv` SHA-256: `{manifest_sha}`")
    w(f"- Programs in manifest: {len(rows)}\n")
    w("> **No program is eligible yet.** All checks here are static (parse-only; no benchmark code "
      "was imported or executed). `execution_verified` is `False` for every row. Eligibility requires "
      "an execution check in the pinned Python 3.10 environment, which has not been built (dependency "
      "installation was not authorised). Paper-protocol details (program lists, categories, LOC "
      "definition) are unverified because the paper's full text has not been read.\n")

    w("## Status definitions\n")
    w("| Status | Meaning |\n|---|---|")
    for s in manifest.STATUSES:
        w(f"| `{s}` | {manifest.STATUS_MEANING[s]} |")
    w("")

    w("## Summary by group\n")
    counts = defaultdict(Counter)
    for r in rows:
        counts[f"{r['set']}/{r['category']}"][r["status"]] += 1
    w("| Group | Programs | " + " | ".join(f"`{s}`" for s in manifest.STATUSES) + " |")
    w("|---|---:|" + "---:|" * len(manifest.STATUSES))
    total = Counter()
    for g in GROUP_ORDER:
        c = counts.get(g, Counter())
        total.update(c)
        w(f"| {g} | {sum(c.values())} | " + " | ".join(str(c[s]) for s in manifest.STATUSES) + " |")
    w(f"| **all** | **{sum(total.values())}** | "
      + " | ".join(f"**{total[s]}**" for s in manifest.STATUSES) + " |\n")
    in_scope = [r for r in rows if r["in_scope"] == "True"]
    w(f"In scope (small + p2): {len(in_scope)} programs; "
      f"`CANDIDATE` {sum(r['status'] == manifest.CANDIDATE for r in in_scope)}, "
      f"`PENDING_CONTEXT` {sum(r['status'] == manifest.PENDING_CONTEXT for r in in_scope)}, "
      f"needing a decision {sum(r['status'].startswith('NEEDS_DECISION') for r in in_scope)}, "
      f"statically ineligible {sum(r['status'].startswith('INELIGIBLE') for r in in_scope)}.\n")

    w("## Observations requiring attention\n")
    dups = [r for r in in_scope if r["duplicate_of"]]
    w(f"- **Duplicate targets** (identical bytes) among in-scope programs: {len(dups)}"
      + ("" if not dups else ": " + "; ".join(f"`{r['program_id']}` = `{r['duplicate_of']}`" for r in dups)))
    dev = [r for r in in_scope if r["dev_test_files"]]
    stub = [r for r in dev if r["dev_test_module_is_stub"] == "True"]
    match = [r for r in dev if r["dev_test_module_matches_target"] == "True"]
    w(f"- **Developer tests**: {len(dev)} small-set programs ship an Exercism `*_test.py`. The module "
      f"it imports is byte-identical to `example.py` in {len(match)} of them; it is an exercise "
      f"**stub** (trivial bodies) in {len(stub)}; the others are non-trivial starter files ("
      + ", ".join(f"`{r['program_id']}`" for r in dev if r not in stub and r not in match)
      + "). Using these tests as a reference oracle would require pointing them at `example.py` "
      "(decision needed later).")
    for s, (lo, hi) in NOMINAL_LOC.items():
        grp = [r for r in rows if r["set"] == s]
        out = [r for r in grp if not (lo <= int(r["physical_lines"]) <= hi and lo <= int(r["sloc"]) <= hi)]
        w(f"- **LOC vs nominal {lo}–{hi} range, set `{s}`** ({len(grp)} programs): "
          f"{len(out)} outside by physical lines or SLOC"
          + (": " + ", ".join(f"`{r['program_id']}` ({r['physical_lines']}/{r['sloc']})" for r in out)
             if out else "")
          + ". The paper's LOC definition is unverified, so this is reported, not used for exclusion.")
    w("- **p2 categories** are not recorded in the repository (`category = unlabelled`); "
      "assigning Cat 2 / Cat 3 needs the paper's rule.")
    w("- The `NEEDS_DECISION_*` and `PENDING_CONTEXT` statuses are not exclusions: those programs stay "
      "in the manifest until you decide how to handle them.\n")

    unresolved = Counter()
    for r in in_scope:
        for name in _split(r["imports_unresolved"]) + _split(r["imports_relative"]) \
                + _split(r["imports_optional_unresolved"]):
            unresolved[name] += 1
    w("## Unresolved imports (in scope)\n")
    w("Names imported by in-scope targets that are neither CPython 3.10 standard library nor present "
      "next to the target. The static check cannot tell a third-party package from a missing sibling "
      "module of the original project.\n")
    w("| Import | Programs |\n|---|---:|")
    for name, n in sorted(unresolved.items(), key=lambda kv: (-kv[1], kv[0])):
        w(f"| `{name}` | {n} |")
    w("")

    w("## Per-program table (in scope)\n")
    w("Columns: physical lines / SLOC; top-level functions / classes / methods; stdlib imports.\n")
    w("| Program | Status | Lines / SLOC | F / C / M | Reasons |\n|---|---|---|---|---|")
    for r in in_scope:
        reasons = "; ".join(_split(r["reasons"])) or "—"
        w(f"| `{r['program_id']}` | `{r['status']}` | {r['physical_lines']} / {r['sloc']} | "
          f"{r['n_functions']} / {r['n_classes']} / {r['n_methods']} | {reasons} |")
    w("")

    p1 = [r for r in rows if r["set"] == "p1"]
    w("## Out of scope (p1, decision 2)\n")
    w(f"{len(p1)} programs are listed in the manifest with status `OUT_OF_SCOPE`; their static facts "
      "are recorded for a possible later extension. "
      f"{sum(bool(r['imports_unresolved']) for r in p1)} of them have unresolved imports.\n")

    ignored = _ignored_files()
    w("## Files in the benchmark tree that are not program targets\n")
    w("Helper scripts from the original authors at set/category level (not analysed as programs):\n")
    for f in ignored:
        w(f"- `{f}`")
    w("")
    return "\n".join(L)


def main() -> int:
    integrity.assert_originals_intact()
    rows = manifest.read_manifest(paths.MANIFEST_CSV)
    out = paths.REPORTS_DIR / "A3_eligibility.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(rows), encoding="utf-8")
    integrity.assert_originals_intact()
    print(json.dumps({"report": out.relative_to(paths.CLEANROOM).as_posix(),
                      "sha256": hashlib.sha256(out.read_bytes()).hexdigest()}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
