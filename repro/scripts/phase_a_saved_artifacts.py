"""Phase A: recompute the paper's results from the artifacts saved in the repository.

No test is executed here; only the saved coverage reports, Pynguin statistics and
pytest logs are parsed. Outputs: repro/results/phase_a/*.csv and summary.json.
"""
from __future__ import annotations

import csv
import statistics as st
from pathlib import Path

from coverage.parser import PythonParser
from scipy import stats

from common import (P2, PAPER, RESULTS, SMALL, classify_structure, parse_coverage_report, rel,
                    write_csv, write_json)

OUT = RESULTS / "phase_a"


def statement_lines(source_path: Path) -> set[int]:
    parser = PythonParser(text=source_path.read_text(), filename=str(source_path))
    parser.parse_source()
    return set(parser.statements)


def small_set() -> list[dict]:
    rows = []
    for cat_dir, cat in (("cat1_scripts", "cat1"), ("cat2_functions", "cat2"), ("cat3_classes", "cat3")):
        for d in sorted((SMALL / cat_dir).iterdir()):
            if not d.is_dir() or d.name == "__pycache__":
                continue
            line = parse_coverage_report(d / "line_coverage.txt", "example")
            branch = parse_coverage_report(d / "branch_coverage.txt", "example")
            stat = d / "pynguin-report" / "statistics.csv"
            pyn = None
            if stat.exists():
                recs = [r for r in csv.reader(stat.open()) if r and r[0] != "TargetModule"]
                pyn = float(recs[-1][1]) * 100 if recs else None
            test = d / "test_example.py"
            rows.append({
                "category": cat, "program": d.name,
                "has_pynguin_tests": test.exists() and "generated by Pynguin" in test.read_text(),
                "developer_tests": ";".join(p.name for p in d.glob("*_test.py")),
                "pynguin_stmt_cov_saved": line["cover"] if line else None,
                "pynguin_branch_cov_saved": branch["cover"] if branch else None,
                "pynguin_report_cov": pyn,
                "structure_rule": classify_structure((d / "example.py").read_text()),
            })
    return rows


def p2_set() -> list[dict]:
    rows = []
    for i in range(1, 44):
        g = P2 / "ChatGPT coverage" / f"sample{i}"
        p = P2 / "pynguin coverage" / f"sample{i}"
        srcs = [s for s in p.glob("*.py") if not s.name.startswith("test_")]
        assert len(srcs) == 1, (i, srcs)
        src = srcs[0]
        mod = src.stem
        p_stmt = [x for x in p.glob("statement_coverage*.txt") if "old" not in x.name]
        p_br = list(p.glob("branch_coverage*.txt"))
        pyn_tests = [t for t in p.glob("test_*.py")]
        gs = parse_coverage_report(g / "statement_coverage.txt", mod)
        gb = parse_coverage_report(g / "branch_coverage.txt", mod)
        ps = parse_coverage_report(p_stmt[0] if p_stmt else None, mod)
        pb = parse_coverage_report(p_br[0] if p_br else None, mod)
        stmts = statement_lines(src)
        row = {
            "sample": f"sample{i}", "module": mod, "source": rel(src),
            "structure_rule": classify_structure(src.read_text()),
            "pynguin_tests_are_pynguin": all("generated by Pynguin" in t.read_text() for t in pyn_tests),
            "pynguin_test_files": ";".join(sorted(t.name for t in pyn_tests)),
            "gpt_stmt": gs["cover"] if gs else None, "gpt_branch": gb["cover"] if gb else None,
            "pyn_stmt": ps["cover"] if ps else None, "pyn_branch": pb["cover"] if pb else None,
            "n_statements": gs["stmts"] if gs else (ps["stmts"] if ps else None),
            "gpt_miss": gs["miss"] if gs else None, "pyn_miss": ps["miss"] if ps else None,
        }
        if gs and ps:
            gm, pm = gs["missed_lines"] & stmts, ps["missed_lines"] & stmts
            row.update({
                "gpt_missed_stmt_lines": len(gm), "pyn_missed_stmt_lines": len(pm),
                "intersect_missed": len(gm & pm), "union_missed": len(gm | pm),
                "missed_lines_match_miss_column": len(gm) == gs["miss"] and len(pm) == ps["miss"],
                # Naive count: every line number inside the "Missing" ranges (includes blank/comment lines).
                "intersect_missed_naive": len(gs["missed_lines"] & ps["missed_lines"]),
                "union_missed_naive": len(gs["missed_lines"] | ps["missed_lines"]),
            })
        rep = g / "compilation_report.txt"
        if rep.exists():
            txt = rep.read_text()
            import re
            m = re.search(r"collected (\d+) items?( / (\d+) errors?)?", txt)
            row["gpt_log_collected"] = int(m.group(1)) if m else None
            row["gpt_log_collection_error"] = bool(m and m.group(2))
            final = re.findall(r"^=+ (.*) in [\d.]+s", txt, re.M)
            for k in ("passed", "failed"):
                mm = re.search(rf"(\d+) {k}", final[-1]) if final else None
                row[f"gpt_log_{k}"] = int(mm.group(1)) if mm else 0
        rows.append(row)
    return rows


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(st.mean(xs), 2) if xs else None


def tests(a, b):
    """Paper's independent t-test plus the paired Wilcoxon signed-rank test."""
    out = {"n": len(a)}
    if len(a) >= 2:
        out["ttest_ind_p"] = round(float(stats.ttest_ind(a, b).pvalue), 3)
        diffs = [x - y for x, y in zip(a, b)]
        if any(diffs):
            out["wilcoxon_p"] = round(float(stats.wilcoxon(a, b).pvalue), 3)
    return out


def main():
    small = small_set()
    write_csv(OUT / "small_set_pynguin_saved.csv", small)
    p2 = p2_set()
    write_csv(OUT / "p2_saved.csv", p2)

    summary = {"small_set": {}, "p2": {}, "notes": []}
    for cat in ("cat1", "cat2", "cat3"):
        rows = [r for r in small if r["category"] == cat]
        summary["small_set"][cat] = {
            "n_programs": len(rows),
            "n_with_pynguin_tests": sum(r["has_pynguin_tests"] for r in rows),
            "pynguin_stmt_mean_coveragepy": mean(r["pynguin_stmt_cov_saved"] for r in rows),
            "pynguin_branch_mean_coveragepy": mean(r["pynguin_branch_cov_saved"] for r in rows),
            "pynguin_report_mean": mean(r["pynguin_report_cov"] for r in rows),
            "paper_pynguin_stmt_branch": PAPER["table1"].get(cat, (None,) * 4)[1::2],
        }

    both = [r for r in p2 if None not in (r["gpt_stmt"], r["pyn_stmt"], r["gpt_branch"], r["pyn_branch"])]
    genuine = [r for r in both if r["pynguin_tests_are_pynguin"]]
    groups = {
        "all_with_both_reports": both,
        "excluding_non_pynguin_suites": genuine,
        "structure_rule_cat2": [r for r in both if r["structure_rule"] == "cat2"],
        "structure_rule_cat3": [r for r in both if r["structure_rule"] == "cat3"],
    }
    for name, rows in groups.items():
        g = {
            "n": len(rows),
            "gpt_stmt": mean(r["gpt_stmt"] for r in rows), "pyn_stmt": mean(r["pyn_stmt"] for r in rows),
            "gpt_branch": mean(r["gpt_branch"] for r in rows), "pyn_branch": mean(r["pyn_branch"] for r in rows),
            "stmt_tests": tests([r["gpt_stmt"] for r in rows], [r["pyn_stmt"] for r in rows]),
            "branch_tests": tests([r["gpt_branch"] for r in rows], [r["pyn_branch"] for r in rows]),
            "intersect_missed_mean": mean(r.get("intersect_missed") for r in rows),
            "union_missed_mean": mean(r.get("union_missed") for r in rows),
            "intersect_missed_naive_mean": mean(r.get("intersect_missed_naive") for r in rows),
            "union_missed_naive_mean": mean(r.get("union_missed_naive") for r in rows),
            "gpt_missed_mean": mean(r.get("gpt_missed_stmt_lines") for r in rows),
            "pyn_missed_mean": mean(r.get("pyn_missed_stmt_lines") for r in rows),
        }
        if g["gpt_missed_mean"] is not None:
            mn, mx = min(g["gpt_missed_mean"], g["pyn_missed_mean"]), max(g["gpt_missed_mean"], g["pyn_missed_mean"])
            g["minimum_missed"] = mn
            # Paper defines these only in words; our reading: statements gained by combining the tools.
            g["minimum_covered_ours"] = round(mn - g["intersect_missed_mean"], 2)
            g["maximum_covered_ours"] = round(mx - g["intersect_missed_mean"], 2)
        summary["p2"][name] = g
    summary["p2"]["excluded_samples_missing_reports"] = [r["sample"] for r in p2 if r not in both]
    summary["p2"]["structure_rule_counts"] = {c: sum(r["structure_rule"] == c for r in p2) for c in ("cat1", "cat2", "cat3")}
    summary["paper"] = {k: PAPER[k] for k in ("table1", "table1_pvalues", "table2", "table2_pvalues", "table5")}
    summary["notes"] = [
        "Category labels for p2 are NOT in the repository; structure_rule_* groups use our AST rule (classes -> cat3).",
        "Missed statements (exact): 'Missing' ranges intersected with executable statement lines (coverage.py PythonParser).",
        "Missed statements (naive): every line number inside the 'Missing' ranges; this reproduces the paper's Table 5 magnitudes.",
        "ChatGPT tests for the small set and the iterative rounds are not in the repository; Tables 1 (ChatGPT), 3 and 4 cannot be recomputed.",
    ]
    write_json(OUT / "summary.json", summary)
    print((OUT / "summary.json").read_text())


if __name__ == "__main__":
    main()
